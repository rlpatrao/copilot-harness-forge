#!/usr/bin/env node
// Install the forge INTO a target project as a self-contained Copilot install
// (BRD v3.5 — in-project install). Usage:
//
//   node scripts/install-to-project.js <target-dir>
//
// Unlike `copilot --plugin-dir` (session-scoped, copies NOTHING into the
// project), this writes the forge's Copilot components into the project so ANY
// Copilot session/surface that opens it recognizes them with no extra flags:
//
//   <target>/.github/agents/*.agent.md        forge agents
//   <target>/.github/skills/*/SKILL.md         forge skills
//   <target>/.github/commands/*.md             forge commands
//   <target>/.github/mcp.json                  MCP servers
//   <target>/.github/copilot-instructions.md   instructions (→ AGENTS.md → CLAUDE.md)
//   <target>/.github/hooks/<event>.json        workspace hook config
//   <target>/.github/hooks/run/<name>.sh       wrappers → .github/forge/hooks/<name>.js
//   <target>/.github/forge/{hooks,scripts,config}/   the forge runtime (code only)
//
// The hooks resolve the USER's project from each event's stdin cwd, and read the
// project's own state/ (feature_list.json, compiled-rules.json, …) — so the
// bundled runtime under .github/forge/ is CODE only; no state is copied.
//
// Platform limit (documented): CLI hooks run only in the Copilot CLI. The IDE
// UI and cloud agent pick up instructions/agents/skills but not the hooks.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { ROOT, EVENT_MAP, ensureDir } = require('./lib/copilot-export.js');
const { collectHookNames } = require('./export-hooks-to-copilot.js');

const HOOK_TIMEOUT_SEC = 30;
const TASK_COMPLETED_TARGET = 'postToolUse';
// Forge runtime dirs copied into <target>/.github/forge/ (code the hooks need).
const RUNTIME_DIRS = ['hooks', 'scripts', 'config'];

function copyTree(srcDir, destDir) {
  ensureDir(destDir);
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const src = path.join(srcDir, entry.name);
    const dest = path.join(destDir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '__tests__' || entry.name === '__fixtures__') continue;
      copyTree(src, dest);
    } else if (entry.isFile()) {
      fs.copyFileSync(src, dest);
      if (entry.name.endsWith('.sh')) fs.chmodSync(dest, 0o755);
    }
  }
}

// In-project hook wrapper. Self-locating: the runtime lives under the project's
// own .github/forge/, and the wrapper sits at .github/hooks/run/<name>.sh, so
// the bundled hook is two levels up under forge/hooks/. Resolving relative to
// the wrapper's own path (not cwd/git/env) is robust to however Copilot invokes
// it. The hook targets the user's project via the event stdin `cwd`.
function targetWrapper(name) {
  return `#!/usr/bin/env bash
# GENERATED by scripts/install-to-project.js — do not edit by hand.
# In-project Copilot hook wrapper for the forge runtime hook ${name}.js.
HERE="$(cd "$(dirname "\${BASH_SOURCE[0]:-$0}")" && pwd)"
COPILOT=1 exec node "$HERE/../../forge/hooks/${name}.js"
`;
}

// Recompute event → deduped hook-script names from settings.json (mirrors
// export-hooks; TaskCompleted folds into postToolUse).
function hooksByEvent() {
  const settings = JSON.parse(fs.readFileSync(path.join(ROOT, 'settings.json'), 'utf8'));
  const hooks = settings.hooks || {};
  const byEvent = {};
  const add = (ev, names) => {
    const bucket = byEvent[ev] || (byEvent[ev] = []);
    const seen = new Set(bucket);
    for (const n of names) if (!seen.has(n)) { seen.add(n); bucket.push(n); }
  };
  for (const [claudeEvent, groups] of Object.entries(hooks)) {
    if (claudeEvent === 'TaskCompleted') { add(TASK_COMPLETED_TARGET, collectHookNames(groups)); continue; }
    const ev = EVENT_MAP[claudeEvent];
    if (ev) add(ev, collectHookNames(groups));
  }
  return byEvent;
}

function main() {
  const target = process.argv[2];
  if (!target) { process.stderr.write('Usage: node scripts/install-to-project.js <target-dir>\n'); process.exit(1); }
  const targetDir = path.resolve(target);
  if (targetDir === ROOT) { process.stderr.write('Refusing to install into the forge repo itself.\n'); process.exit(1); }
  ensureDir(targetDir);

  // 1. Ensure the forge's .github/ component trees are fresh.
  execFileSync('node', [path.join(ROOT, 'scripts', 'export-to-copilot.js')], { stdio: 'ignore' });

  // 2. Copy the generated component trees + instructions into <target>/.github/.
  const srcGh = path.join(ROOT, '.github');
  const dstGh = path.join(targetDir, '.github');
  for (const sub of ['agents', 'skills', 'commands']) copyTree(path.join(srcGh, sub), path.join(dstGh, sub));
  ensureDir(dstGh);
  for (const f of ['mcp.json', 'copilot-instructions.md']) {
    fs.copyFileSync(path.join(srcGh, f), path.join(dstGh, f));
  }

  // 3. Copy the forge runtime (code only) into <target>/.github/forge/.
  const forgeHome = path.join(dstGh, 'forge');
  for (const d of RUNTIME_DIRS) copyTree(path.join(ROOT, d), path.join(forgeHome, d));

  // 4. Generate workspace hook config + in-project wrappers.
  const byEvent = hooksByEvent();
  const hooksDir = path.join(dstGh, 'hooks');
  const runDir = path.join(hooksDir, 'run');
  ensureDir(runDir);
  const allNames = new Set(Object.values(byEvent).flat());
  for (const name of allNames) {
    const wp = path.join(runDir, `${name}.sh`);
    fs.writeFileSync(wp, targetWrapper(name));
    fs.chmodSync(wp, 0o755);
  }
  for (const [event, names] of Object.entries(byEvent)) {
    const entries = names.map((name) => ({ type: 'command', bash: `./run/${name}.sh`, cwd: '.github/hooks', timeoutSec: HOOK_TIMEOUT_SEC }));
    fs.writeFileSync(path.join(hooksDir, `${event}.json`), JSON.stringify({ version: 1, hooks: { [event]: entries } }, null, 2) + '\n');
  }

  const nSkills = fs.readdirSync(path.join(dstGh, 'skills')).length;
  const nAgents = fs.readdirSync(path.join(dstGh, 'agents')).length;
  process.stdout.write(
    `install-to-project: forge installed into ${targetDir}\n` +
    `  .github/agents/ (${nAgents})  .github/skills/ (${nSkills})  .github/hooks/ (${Object.keys(byEvent).length} events, ${allNames.size} wrappers)\n` +
    `  .github/forge/ runtime: ${RUNTIME_DIRS.join(', ')}\n\n` +
    `Next:\n` +
    `  cd ${target} && git add .github && git commit -m "chore: install harness-forge (Copilot)"\n` +
    `  copilot        # accept the folder-trust prompt (enables hooks); no --plugin-dir needed\n`
  );
}

if (require.main === module) {
  try { main(); } catch (e) { process.stderr.write(`install-to-project FAILED: ${e.message}\n`); process.exit(1); }
}
module.exports = { targetWrapper, hooksByEvent };
