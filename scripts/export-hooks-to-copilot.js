#!/usr/bin/env node
// Export Claude Code hook config → Copilot CLI hook config (BRD v3.5 §6b / §3).
//
//   Reads:  settings.json  (the `hooks` block)
//   Writes: .github/hooks/<copilotEvent>.json   (one file per Copilot event)
//           .github/hooks/run/<name>.sh         (one bash wrapper per hook)
//
// SCHEMA VERIFIED against Copilot CLI 1.0.73 during the v3.5 dogfood (a probe
// hook fired only in this exact shape). Copilot's format is NOT Claude's:
//
//   {
//     "version": 1,
//     "hooks": {
//       "sessionStart": [
//         { "type": "command", "bash": "./run/session-start.sh",
//           "cwd": ".github/hooks", "timeoutSec": 30 }
//       ]
//     }
//   }
//
// Differences that broke the first attempt:
//   - top-level { version, hooks:{…} } wrapper (not a bare { "<event>": […] })
//   - each entry uses `bash` = a SCRIPT PATH (not `command` = a shell string)
//   - `cwd` is relative to the repo root; `bash` is relative to `cwd`
//   - NO `matcher` field in Copilot's file schema — every hook for an event
//     fires on every occurrence, so hooks self-filter on tool_input (they
//     already no-op when the tool/path is irrelevant). Claude's per-matcher
//     groups are therefore UNIONed per event here.
//
// Because Copilot invokes a bash script (not an inline command), we emit a thin
// wrapper per hook that sets COPILOT=1 (→ flat output shape) and execs the node
// hook from the repo root so hooks/lib/fire-log.js resolves state/.
//
// RUNTIME REQUIREMENT: Copilot only runs repo hooks in a TRUSTED folder
// (gated by `isFolderTrusted`). Trust the repo once interactively, or seed
// ~/.copilot/settings.json `trustedFolders`. Documented in the runbook.
//
// Idempotent. Exit 0 on success, 1 on structural error.

const fs = require('fs');
const path = require('path');
const { ROOT, OUT, EVENT_MAP, ensureDir } = require('./lib/copilot-export.js');

// TaskCompleted has no Copilot event; its hooks fold into postToolUse (they
// self-filter, so no matcher is needed under Copilot's matcher-less schema).
const TASK_COMPLETED_TARGET = 'postToolUse';
const HOOK_TIMEOUT_SEC = 30;

function hookScriptName(command) {
  const m = /([A-Za-z0-9_-]+)\.js/.exec(command || '');
  return m ? m[1] : null; // basename without extension
}

// Union of hook script names for a Claude event's matcher groups, order-preserved.
function collectHookNames(groups) {
  const seen = new Set();
  const names = [];
  for (const g of groups) {
    for (const h of g.hooks || []) {
      const name = hookScriptName(h.command);
      if (name && !seen.has(name)) { seen.add(name); names.push(name); }
    }
  }
  return names;
}

function wrapperScript(name) {
  // Dual-mode wrapper (v3.5). Resolves the forge root two ways so the same
  // wrapper works whether the forge is loaded as a Copilot PLUGIN or run
  // self-hosted:
  //   - Plugin mode:  Copilot sets $COPILOT_PLUGIN_ROOT to the plugin dir (the
  //     forge). We run the forge's bundled hooks/<name>.js from there, so hooks
  //     work in ANY project the plugin is loaded into.
  //   - Self-hosted:  $COPILOT_PLUGIN_ROOT is unset → fall back to the git root
  //     (the forge repo itself).
  // The hook itself targets the USER'S project via the `cwd` field in the event
  // stdin payload (verified: Copilot passes the session cwd there), NOT via the
  // process cwd. COPILOT=1 selects the flat output shape; exec preserves stdin.
  return `#!/usr/bin/env bash
# GENERATED by scripts/export-hooks-to-copilot.js — do not edit by hand.
# Copilot hook wrapper for hooks/${name}.js (v3.5 Copilot port).
ROOT="\${COPILOT_PLUGIN_ROOT:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
COPILOT=1 exec node "$ROOT/hooks/${name}.js"
`;
}

function main() {
  const settings = JSON.parse(fs.readFileSync(path.join(ROOT, 'settings.json'), 'utf8'));
  const hooks = settings.hooks || {};

  // copilotEvent -> ordered, de-duped hook script names
  const byEvent = {};
  const addNames = (copilotEvent, names) => {
    const bucket = byEvent[copilotEvent] || (byEvent[copilotEvent] = []);
    const seen = new Set(bucket);
    for (const n of names) if (!seen.has(n)) { seen.add(n); bucket.push(n); }
  };

  for (const [claudeEvent, groups] of Object.entries(hooks)) {
    if (claudeEvent === 'TaskCompleted') { addNames(TASK_COMPLETED_TARGET, collectHookNames(groups)); continue; }
    const copilotEvent = EVENT_MAP[claudeEvent];
    if (!copilotEvent) { process.stderr.write(`WARN: no Copilot event mapping for "${claudeEvent}" — skipped\n`); continue; }
    addNames(copilotEvent, collectHookNames(groups));
  }

  ensureDir(OUT.hooks);
  const runDir = path.join(OUT.hooks, 'run');
  ensureDir(runDir);
  // Clear stale generated files.
  for (const f of fs.readdirSync(OUT.hooks).filter((f) => f.endsWith('.json'))) fs.unlinkSync(path.join(OUT.hooks, f));
  for (const f of fs.readdirSync(runDir).filter((f) => f.endsWith('.sh'))) fs.unlinkSync(path.join(runDir, f));

  // Emit one bash wrapper per unique hook script.
  const allNames = new Set(Object.values(byEvent).flat());
  for (const name of allNames) {
    const wp = path.join(runDir, `${name}.sh`);
    fs.writeFileSync(wp, wrapperScript(name));
    fs.chmodSync(wp, 0o755);
  }

  let written = 0;
  for (const [copilotEvent, names] of Object.entries(byEvent)) {
    const entries = names.map((name) => ({
      type: 'command',
      bash: `./run/${name}.sh`,
      cwd: '.github/hooks',
      timeoutSec: HOOK_TIMEOUT_SEC,
    }));
    const doc = { version: 1, hooks: { [copilotEvent]: entries } };
    fs.writeFileSync(path.join(OUT.hooks, `${copilotEvent}.json`), JSON.stringify(doc, null, 2) + '\n');
    written++;
    process.stdout.write(`  .github/hooks/${copilotEvent}.json  (${entries.length} hook(s))\n`);
  }

  // Consolidated PLUGIN hooks config (v3.5). plugin.json's `hooks` field takes a
  // single file; workspace-mode auto-load only scans .github/hooks/*.json, so
  // this lives one level up at .github/plugin-hooks.json to avoid double-loading.
  // Entries reference the wrappers through ${COPILOT_PLUGIN_ROOT} so they resolve
  // to the plugin's bundled scripts from inside ANY project.
  const pluginHooks = {};
  for (const [copilotEvent, names] of Object.entries(byEvent)) {
    pluginHooks[copilotEvent] = names.map((name) => ({
      type: 'command',
      bash: `\${COPILOT_PLUGIN_ROOT}/.github/hooks/run/${name}.sh`,
      timeoutSec: HOOK_TIMEOUT_SEC,
    }));
  }
  const pluginHooksPath = path.join(ROOT, '.github', 'plugin-hooks.json');
  fs.writeFileSync(pluginHooksPath, JSON.stringify({ version: 1, hooks: pluginHooks }, null, 2) + '\n');

  process.stdout.write(`export-hooks: ${written} workspace event file(s) + .github/plugin-hooks.json + ${allNames.size} bash wrapper(s)\n`);
}

if (require.main === module) {
  try { main(); } catch (e) { process.stderr.write(`export-hooks FAILED: ${e.message}\n`); process.exit(1); }
}
module.exports = { hookScriptName, collectHookNames, wrapperScript };
